import type { ConversationExportChunk, ConversationExportIrRow } from "@acode/services";
import { formatAttachmentSize } from "@/lib/chatAttachmentMetadata.js";
import { normalizeConversationShareMarkdown } from "@/v4/conversationShareMarkdown.js";
import {
  formatExportDuration,
  formatExportTimestamp,
  type ConversationExportLabels,
} from "@/lib/conversation-export/conversationExportLabels.js";
import type { Locale } from "@acode/shared";

/**
 * IR 分片 → Markdown（纯字符串拼接，无 IO、无 DOM）。
 *
 * 行类型 → 表示形式的权威映射表在 `packages/ui/src/v4/ConversationShareReadonlyTimeline.tsx`
 * 的 `renderReadonlyRow`（:522-591）；本文件按同一 switch 结构实现同一套语义。
 *
 * 正文一律经 `normalizeConversationShareMarkdown` 处理：剥离本地 citation directive（防路径泄漏）
 * 并把远程图片降级为链接（防打开即向第三方发起请求）。
 */

export interface ConversationExportSerializeContext {
  labels: ConversationExportLabels;
  locale: Locale;
  intl: IntlInstance;
  /** artifactVersionId/logicalKey → displayName；供 citation 剥离把 directive 换成显示名。 */
  artifactNames: ReadonlyMap<string, string>;
  /** 轮次序号计数器；跨分片累加，保证「第 N 轮」在整份文件里连续。 */
  turnCounter: { value: number };
}

/**
 * 统计行首的三反引号围栏数量；为奇数时补一个闭合围栏。
 *
 * 模型正文可能给出未闭合的代码围栏（E12）。若不补，后续所有小节都会被 Markdown 阅读器
 * 吞进代码块，整份导出不可读。这里只处理行首（允许缩进）的 ``` 围栏，不碰行内反引号。
 */
export function balanceMarkdownCodeFences(markdown: string): string {
  let fenceCount = 0;
  for (const line of markdown.split("\n")) {
    if (/^\s*```/u.test(line)) fenceCount += 1;
  }
  return fenceCount % 2 === 1 ? `${markdown}\n\`\`\`` : markdown;
}

function normalizeBody(text: string, artifactNames: ReadonlyMap<string, string>): string {
  return balanceMarkdownCodeFences(normalizeConversationShareMarkdown(text, artifactNames));
}

/** 工具输出在 Markdown 里用围栏代码块承载；围栏长度按内容自适应，避免内容里的 ``` 提前闭合。 */
function fenceFor(content: string): string {
  const longestRun = Math.max(0, ...[...content.matchAll(/`+/gu)].map((match) => match[0].length));
  return "`".repeat(Math.max(3, longestRun + 1));
}

function serializeRow(
  row: ConversationExportIrRow,
  context: ConversationExportSerializeContext,
): string {
  const { labels, locale, intl, artifactNames } = context;
  switch (row.kind) {
    case "turnHeader": {
      context.turnCounter.value += 1;
      const duration = formatExportDuration(row.durationMs, intl, locale);
      const time = formatExportTimestamp(row.startedAt, locale);
      return `\n---\n\n### ${labels.turnHeading(context.turnCounter.value, time, duration)}\n\n`;
    }
    case "userInput": {
      const parts = [`\n## 👤 ${labels.userHeading}\n\n`];
      const body = normalizeBody(row.text, artifactNames).trim();
      if (body) parts.push(`${body}\n\n`);
      for (const attachment of row.attachments) {
        parts.push(
          `- 📎 ${labels.attachmentMeta(
            attachment.fileName,
            formatAttachmentSize(attachment.sizeBytes),
          )}\n`,
        );
      }
      if (row.attachments.length > 0) parts.push("\n");
      return parts.join("");
    }
    case "assistantText": {
      const body = normalizeBody(row.text, artifactNames).trim();
      return `\n## 🤖 ${labels.assistantHeading}\n\n${body}\n\n`;
    }
    case "reasoning": {
      const duration = formatExportDuration(row.durationMs, intl, locale);
      const body = normalizeBody(row.text, artifactNames).trim();
      return `\n<details>\n<summary>${labels.reasoningSummary(duration)}</summary>\n\n${body}\n\n</details>\n\n`;
    }
    case "toolCall": {
      const kindLabel = labels.toolKindLabel(row.family, row.toolName);
      const statusLabel = labels.toolStatusLabel(row.status);
      const summary = `${kindLabel} · ${statusLabel} · ${row.toolName}`;
      const output = normalizeBody(row.outputText, artifactNames).trim();
      const truncatedNote =
        row.truncatedChars === undefined
          ? ""
          : `\n\n${labels.toolOutputTruncated(row.truncatedChars)}`;
      const fence = fenceFor(output);
      return `\n<details>\n<summary>${summary}</summary>\n\n${fence}\n${output}\n${fence}${truncatedNote}\n\n</details>\n\n`;
    }
    case "artifact": {
      return `\n- 📄 ${labels.artifactMeta(row.artifactType, formatAttachmentSize(row.sizeBytes))}\n\n`;
    }
    case "timelineMarker": {
      const label = row.markerType === "compact" ? labels.markerCompact : labels.markerModelChange;
      return `\n---\n\n${label}\n\n`;
    }
  }
}

export function serializeConversationMarkdownHead(options: {
  title: string;
  labels: ConversationExportLabels;
}): string {
  const title = options.title.trim() || "ACode";
  return `# ${title}\n\n<!-- Generated by ACode. Self-contained, no scripts, no network requests. -->\n\n`;
}

export function serializeConversationMarkdownChunk(
  chunk: ConversationExportChunk,
  context: ConversationExportSerializeContext,
): string {
  let output = "";
  for (const row of chunk.rows) {
    output += serializeRow(row, context);
  }
  return output;
}

export function serializeConversationMarkdownTail(
  skippedRowCount: number,
  labels: ConversationExportLabels,
): string {
  if (skippedRowCount <= 0) return "";
  return `\n---\n\n${labels.skipped(skippedRowCount)}\n`;
}
