// ============================================================
// Skill Live Build Section（specs/guide-live-build-section.md）
// ============================================================
// T2-c2「Current Build」实时自知：技能正文含 {{ACODE_CURRENT_BUILD}} 占位符时，
// Skill 工具装配点（skill.ts）调用本模块，把占位符替换为「运行中 CLI」生成的快照节。
// 动机（实证见 spec 背景节）：纯静态技能文档在快速迭代的产品里必然漂移——guide 技能
// 曾把 .acode 配置路径写成 .zcode、把 MCP 同名覆盖方向写反。实时节让模型把当前构建
// 的事实当 ground truth，静态正文只保留结构性地图。
//
// 本文件是注入/缓存/渲染面；事实采集在 ./skill-live-build-collect.ts。
// 纪律：
// - R1 占位符是唯一 opt-in 面，无占位符零成本透传；
// - R3 子节失败标注「unavailable this time」而非缺失；注入自身永不抛错；
// - R4 成功快照按 sessionId 缓存（LRU 上限 16），version 变化即失效；降级不缓存。

import {
  collectLiveBuildSnapshot,
  errorMessage,
  type LiveBuildInjectionInput,
  type LiveBuildSnapshot,
  type Subsection,
} from "./skill-live-build-collect.js";

// 测试与二次消费面：采集类型与入口从注入模块透出，避免深引用兄弟文件。
export { collectLiveBuildSnapshot } from "./skill-live-build-collect.js";
export type {
  LiveBuildInjectionInput,
  LiveBuildSnapshot,
  Subsection,
} from "./skill-live-build-collect.js";

/** 技能正文中的实时节占位符（R1）。 */
export const LIVE_BUILD_PLACEHOLDER = "{{ACODE_CURRENT_BUILD}}";

/** 子节降级标注文案（R3）：与 SKILL.md 学说中的措辞保持一致。 */
const UNAVAILABLE_MARK = "unavailable this time";

/** 会话缓存上限（R4）：长驻进程服务多会话，防无界增长；Map 插入序即 LRU 序。 */
const CACHE_MAX_SESSIONS = 16;

interface CacheEntry {
  version: string | undefined;
  section: string;
}

const sessionCache = new Map<string, CacheEntry>();

/** 测试专用：清空会话缓存。 */
export function clearLiveBuildSectionCache(): void {
  sessionCache.clear();
}

/**
 * R1+R4+R5 主入口：占位符替换。永不抛错——任何失败都落到降级节（R3），
 * 不能让快照机制反过来弄挂 Skill 调用。
 */
export async function injectLiveBuildSection(
  content: string,
  input: LiveBuildInjectionInput,
): Promise<string> {
  // R1：无占位符零成本透传——绝大多数技能与本机制无关，不付出任何采集开销。
  if (!content.includes(LIVE_BUILD_PLACEHOLDER)) return content;

  const cacheKey = input.sessionId ?? "__anonymous__";
  const cached = readCache(cacheKey, input.version);
  if (cached !== undefined) {
    return content.split(LIVE_BUILD_PLACEHOLDER).join(cached);
  }

  let section: string;
  try {
    section = renderLiveBuildSection(await collectLiveBuildSnapshot(input));
    writeCache(cacheKey, input.version, section);
  } catch (error) {
    // R3 节级降级：降级结果不进缓存（R4），瞬态失败可在会话内自愈。
    section = renderDegradedSection(errorMessage(error));
  }
  return content.split(LIVE_BUILD_PLACEHOLDER).join(section);
}

function readCache(sessionId: string, version: string | undefined): string | undefined {
  const entry = sessionCache.get(sessionId);
  if (!entry) return undefined;
  // R4：宿主提供 version 时，版本变化即失效重采；version 缺席则退化为会话级缓存。
  if (entry.version !== version) return undefined;
  return entry.section;
}

function writeCache(sessionId: string, version: string | undefined, section: string): void {
  if (!sessionCache.has(sessionId) && sessionCache.size >= CACHE_MAX_SESSIONS) {
    const oldest = sessionCache.keys().next();
    if (!oldest.done) sessionCache.delete(oldest.value);
  }
  sessionCache.delete(sessionId); // 重插到尾部，维持 LRU 序
  sessionCache.set(sessionId, { version, section });
}

// -----------------------------------------------
// 渲染（纯函数；节文本为英文以与技能正文语言一致）
// -----------------------------------------------

export function renderLiveBuildSection(snapshot: LiveBuildSnapshot): string {
  const lines: string[] = [
    "<!-- BEGIN Current Build: generated at runtime by the running CLI. Do not recite it from memory. -->",
    "## Current Build (live snapshot)",
    "",
    `Generated by the running CLI at ${snapshot.generatedAt}. This section is ground truth about the CURRENT build: when it conflicts with your training data or with static text in this skill, this section wins.`,
    "",
    `- Version: ${inline(snapshot.version)}`,
    "",
    "### Tools visible to the agent",
    ...listBlock(snapshot.tools, (tools) => [tools.map((tool) => `\`${tool}\``).join(", ")]),
    "",
    "### Slash commands",
    // 宿主接线②：command-center 注册表投影在场即渲染 runtime truth；缺席保持既有
    // 降级注记逐字不变（tests/guide-live-build-section.test.mjs 钉住的文案）。
    ...(snapshot.builtInCommands.available
      ? listBlock(snapshot.builtInCommands, (items) => [
          "Built-in slash command table (runtime truth from the CLI command registry):",
          ...items.map((name) => `- ${name}`),
        ])
      : [
          `- Built-in slash command table: ${UNAVAILABLE_MARK} — the CLI-side command registry is not wired into this snapshot yet.`,
        ]),
    ...listBlock(snapshot.customCommands, (items) => [
      "Custom commands discovered on disk (best-effort scan of the well-known command roots):",
      ...items,
    ]),
    "",
    "### Installed skills",
    ...listBlock(snapshot.skills),
    "",
    "### Installed agents (user and workspace markdown profiles)",
    ...listBlock(snapshot.agents, (items) => [
      ...items,
      // 宿主接线④：bundled/plugin 投影在场即收起「not visible」降级注记。
      ...(snapshot.agentsIncludeHostProjection
        ? []
        : ["Plugin-provided and bundled agents are not visible to this snapshot."]),
    ]),
    "",
    // 宿主接线③：连接态投影在场时标题如实升级为 runtime 措辞（行内 runtime: <state>）。
    snapshot.mcpConnectionStatesVisible
      ? "### MCP servers (runtime connection state where visible)"
      : "### MCP servers (configured; connection state is not visible here)",
    ...listBlock(snapshot.mcpServers),
    "",
    "### Configured settings keys (names only — values are never shown)",
    ...listBlock(snapshot.settingsKeys),
    "",
    `Subsections marked "${UNAVAILABLE_MARK}" are degraded, not absent: the fact could not be collected in this session. Disk-scanned subsections are a best-effort approximation of the real discovery pipeline. This section is generated once per session and re-generated when the CLI version changes.`,
    "<!-- END Current Build -->",
  ];
  return lines.join("\n");
}

/** 节级降级（R3）：占位符仍被替换，指引回退 references + 显式声明训练数据用法。 */
export function renderDegradedSection(reason: string): string {
  return [
    "<!-- BEGIN Current Build (degraded) -->",
    `## Current Build — ${UNAVAILABLE_MARK}`,
    "",
    `The running CLI could not generate the live snapshot for this session (${reason}).`,
    "Fall back to the bundled references (references/recent-changes.md) and, if you must answer from training data, declare that explicitly and warn that it may be outdated.",
    "<!-- END Current Build -->",
  ].join("\n");
}

function inline(subsection: Subsection<string>): string {
  return subsection.available ? subsection.value : `${UNAVAILABLE_MARK} — ${subsection.reason}`;
}

function listBlock(
  subsection: Subsection<string[] | readonly string[]>,
  format?: (items: readonly string[]) => string[],
): string[] {
  if (!subsection.available) {
    return [`_${UNAVAILABLE_MARK} — ${subsection.reason}_`];
  }
  const items = subsection.value;
  if (items.length === 0) return ["_(none discovered)_"];
  return format ? format(items) : [...items];
}
